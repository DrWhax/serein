#!/usr/bin/env node
// Generates Packages/SignalUI/Sources/SignalUI/Tokens/SignalIcons.generated.swift from
// upstream's bundled SVG icons (Signal-Desktop/images/icons/**/*.svg, trusted build-time
// input). Each icon is its size, viewBox and paths (path data, fill rule, fill colour;
// black fills are "template" and take the caller's colour, like the SCSS color-svg
// mask). Full-viewBox clipPaths are dropped; anything else unsupported fails the build.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = join(root, 'Signal-Desktop/images');
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (p.endsWith('.svg')) files.push(p); } };
walk(join(base, 'icons'));
// Top-level single-colour images used as masks by ported components.
for (const f of ['alert-outline.svg', 'file.svg', 'image.svg', 'movie.svg', 'signal-logo.svg']) files.push(join(base, f));
// Multi-colour illustrations whose paths are coloured by <style> class rules (none yet).
for (const f of []) files.push(join(base, f));
files.sort();
const out = ['// Generated by Tools/gen-icons.mjs from Signal-Desktop/images/icons. Do not edit.', '', 'import CoreGraphics', '', 'enum SignalIconsTable {',
  '    static let icons: [String: SignalIconData] = ['];
let count = 0, skipped = [];
const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const hex = (c) => {
  if (!c || c === 'none') return null;
  if (c === '#000' || c === '#000000' || c === 'black' || c === 'currentColor') return 'nil';
  const m = c.match(/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/);
  if (!m) return undefined;
  const x = m[1].length === 3 ? m[1].split('').map((ch) => ch + ch).join('') : m[1];
  return `RGBA(hex: 0x${x})`;
};
for (const f of files) {
  let svg = readFileSync(f, 'utf8');
  const name = relative(base, f).replace(/^icons\//, '').replace(/\.svg$/, '');
  // Inline `<style>` class fills (`.a,.b{…}.a{fill:#…}`) as fill attributes, then drop the style.
  const style = svg.match(/<style>([\s\S]*?)<\/style>/)?.[1];
  if (style) {
    const fills = {};
    for (const [, sel, body] of style.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
      const fill = body.match(/fill:\s*([^;]+)/)?.[1]?.trim();
      if (fill) for (const c of sel.split(',')) fills[c.trim().replace(/^\./, '')] = fill;
    }
    svg = svg.replace(/<style>[\s\S]*?<\/style>/, '').replace(/<defs>\s*<\/defs>/, '')
      .replace(/\sclass="([^"]*)"/g, (_, c) => (fills[c] ? ` fill="${fills[c]}"` : ''));
  }
  svg = svg.replace(/<defs>[\s\S]*?<\/defs>/g, (defs) => {
    if (/<clipPath[^>]*><path[^>]*d="M0 0h(\d+(?:\.\d+)?)v(\d+(?:\.\d+)?)H0z"\/><\/clipPath>/.test(defs) && !/<(linearGradient|radialGradient|mask|filter)/.test(defs)) return '';
    return defs;
  });
  if (/<(defs|mask|linearGradient|radialGradient|filter|use|circle|rect|ellipse|polygon|polyline|line|text|image)[\s>]/.test(svg) || /transform=/.test(svg)) {
    skipped.push(name);
    continue;
  }
  const svgTag = svg.match(/<svg[^>]*>/)[0];
  const w = parseFloat(attr(svgTag, 'width') ?? '0'), h = parseFloat(attr(svgTag, 'height') ?? '0');
  const vb = (attr(svgTag, 'viewBox') ?? `0 0 ${w} ${h}`).split(/[\s,]+/).map(Number);
  const rootFill = attr(svgTag, 'fill');
  const paths = [];
  let bad = false;
  for (const m of svg.matchAll(/<path[^>]*>/g)) {
    const t = m[0];
    const d = attr(t, 'd');
    const fill = attr(t, 'fill') ?? (rootFill && rootFill !== 'none' ? rootFill : '#000');
    const color = hex(fill);
    if (!d || color === undefined || attr(t, 'stroke')) { bad = true; break; }
    if (color === null) continue;
    paths.push(`.init(d: "${d}", evenOdd: ${attr(t, 'fill-rule') === 'evenodd'}, color: ${color})`);
  }
  if (bad || !paths.length) { skipped.push(name); continue; }
  out.push(`        "${name}": SignalIconData(width: ${w || vb[2]}, height: ${h || vb[3]}, viewBox: CGRect(x: ${vb[0]}, y: ${vb[1]}, width: ${vb[2]}, height: ${vb[3]}), paths: [`);
  for (const p of paths) out.push(`            ${p},`);
  out.push('        ]),');
  count++;
}
// Avatar preset icons (images/avatars, drawn by avatarDataToBytes): multi-colour paths with
// fills inherited from <g>, circles, strokes and a full-viewBox clip. Black stays black.
{
  const dir = join(base, 'avatars');
  const color = (c) => {
    if (!c || c === 'none') return null;
    if (c === 'black') c = '#000';
    if (c === 'white') c = '#fff';
    const m = c.match(/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/);
    if (!m) throw new Error(`avatar colour ${c}`);
    const x = m[1].length === 3 ? m[1].split('').map((ch) => ch + ch).join('') : m[1];
    return `RGBA(hex: 0x${x})`;
  };
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
    let svg = readFileSync(join(dir, file), 'utf8');
    svg = svg.replace(/<defs>[\s\S]*?<\/defs>/g, '').replace(/<clipPath[^>]*><path[^>]*d="M0 0h56v56H0z"\/><\/clipPath>/g, '')
      .replace(/\sclip-path="url\(#a\)"/g, '');
    if (/<(mask|linearGradient|radialGradient|filter|use|rect|ellipse|polygon|polyline|line|text|image|clipPath)[\s>]/.test(svg) || /transform=/.test(svg)) {
      throw new Error(`unsupported avatar ${file}`);
    }
    const svgTag = svg.match(/<svg[^>]*>/)[0];
    const vb = attr(svgTag, 'viewBox').split(/[\s,]+/).map(Number);
    const fills = [attr(svgTag, 'fill') ?? '#000'];
    const paths = [];
    for (const m of svg.matchAll(/<(\/?)(g|path|circle)\b([^>]*?)(\/?)>/g)) {
      const [, close, tag, rest, selfClose] = m;
      const t = `<${tag}${rest}>`;
      if (tag === 'g') {
        if (close) fills.pop(); else if (!selfClose) fills.push(attr(t, 'fill') ?? fills[fills.length - 1]);
        continue;
      }
      if (close) continue;
      let d = attr(t, 'd');
      if (tag === 'circle') {
        const cx = +attr(t, 'cx'), cy = +attr(t, 'cy'), r = +attr(t, 'r');
        d = `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
      }
      const fill = attr(t, 'fill') ?? fills[fills.length - 1];
      const fc = color(fill), sc = color(attr(t, 'stroke'));
      if (!fc && !sc) continue;
      let spec = `.init(d: "${d}", evenOdd: ${attr(t, 'fill-rule') === 'evenodd'}, color: ${fc ?? 'nil'}`;
      if (!fc) spec += ', filled: false';
      if (sc) spec += `, stroke: ${sc}, strokeWidth: ${attr(t, 'stroke-width') ?? 1}, miterLimit: ${attr(t, 'stroke-miterlimit') ?? 4}`;
      paths.push(spec + ')');
    }
    out.push(`        "avatars/${file.replace(/\.svg$/, '')}": SignalIconData(width: ${vb[2]}, height: ${vb[3]}, viewBox: CGRect(x: ${vb[0]}, y: ${vb[1]}, width: ${vb[2]}, height: ${vb[3]}), paths: [`);
    for (const p of paths) out.push(`            ${p},`);
    out.push('        ]),');
    count++;
  }
}

// Multi-colour 40px illustrations (UsernameOnboardingModal): paths, circles and rects
// (rx; `rotate(a cx cy)`), fills inherited from <g>, strokes, a full-viewBox clip. Black stays black.
{
  const color = (c, opacity) => {
    if (!c || c === 'none') return null;
    if (c === 'black') c = '#000';
    if (c === 'white') c = '#fff';
    const m = c.match(/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/);
    if (!m) throw new Error(`illustration colour ${c}`);
    const x = m[1].length === 3 ? m[1].split('').map((ch) => ch + ch).join('') : m[1];
    return opacity != null && +opacity !== 1 ? `RGBA(hex: 0x${x}, alpha: ${+opacity})` : `RGBA(hex: 0x${x})`;
  };
  const illustrations = ['tag_light', 'tag_dark', 'phone_40_color', 'phone_40_color_dark', 'usernames_40_color', 'usernames_40_color_dark', 'qr_codes_40_color', 'qr_codes_40_color_dark', 'macos-switch',
    ...readdirSync(join(base, 'safety-tips')).filter((f) => f.endsWith('.svg')).sort().map((f) => 'safety-tips/' + f.replace(/\.svg$/, ''))];
  for (const file of illustrations) {
    let svg = readFileSync(join(base, file + '.svg'), 'utf8');
    svg = svg.replace(/<defs>[\s\S]*?<\/defs>/g, (defs) => {
      if (/<clipPath[^>]*><path[^>]*d="M0 0h40v40H0z"[^>]*\/><\/clipPath>/.test(defs)) return '';
      throw new Error(`unsupported defs in ${file}`);
    }).replace(/\sclip-path="url\(#a\)"/g, '');
    if (/<(mask|linearGradient|radialGradient|filter|use|ellipse|polygon|polyline|line|text|image|clipPath)[\s>]/.test(svg)) throw new Error(`unsupported ${file}`);
    const svgTag = svg.match(/<svg[^>]*>/)[0];
    const w = parseFloat(attr(svgTag, 'width')), h = parseFloat(attr(svgTag, 'height'));
    if (attr(svgTag, 'viewBox') && attr(svgTag, 'viewBox') !== `0 0 ${w} ${h}`) throw new Error(`viewBox in ${file}`);
    const rootFill = attr(svgTag, 'fill');
    const fills = [rootFill ?? '#000'];
    const paths = [];
    for (const m of svg.matchAll(/<(\/?)(g|path|circle|rect)\b([^>]*?)(\/?)>/g)) {
      const [, close, tag, rest, selfClose] = m;
      const t = `<${tag}${rest}>`;
      if (tag === 'g') {
        if (close) fills.pop(); else if (!selfClose) fills.push(attr(t, 'fill') ?? fills[fills.length - 1]);
        continue;
      }
      if (close) continue;
      let d = attr(t, 'd');
      if (tag === 'circle') {
        const cx = +attr(t, 'cx'), cy = +attr(t, 'cy'), r = +attr(t, 'r');
        d = `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
      }
      if (tag === 'rect') {
        const x = +(attr(t, 'x') ?? 0), y = +(attr(t, 'y') ?? 0), rw = +attr(t, 'width'), rh = +attr(t, 'height'), rx = +(attr(t, 'rx') ?? 0);
        d = `M${x + rx} ${y}h${rw - 2 * rx}a${rx} ${rx} 0 0 1 ${rx} ${rx}v${rh - 2 * rx}a${rx} ${rx} 0 0 1 ${-rx} ${rx}h${-(rw - 2 * rx)}a${rx} ${rx} 0 0 1 ${-rx} ${-rx}v${-(rh - 2 * rx)}a${rx} ${rx} 0 0 1 ${rx} ${-rx}z`;
      }
      const fill = attr(t, 'fill') ?? fills[fills.length - 1];
      const fc = color(fill, attr(t, 'fill-opacity') ?? attr(t, 'opacity')), sc = color(attr(t, 'stroke'), attr(t, 'stroke-opacity'));
      if (!fc && !sc) continue;
      let spec = `.init(d: "${d}", evenOdd: ${attr(t, 'fill-rule') === 'evenodd'}, color: ${fc ?? 'nil'}`;
      if (!fc) spec += ', filled: false';
      if (sc) spec += `, stroke: ${sc}, strokeWidth: ${attr(t, 'stroke-width') ?? 1}, miterLimit: ${attr(t, 'stroke-miterlimit') ?? 4}`;
      const tr = attr(t, 'transform');
      if (tr) {
        const r = tr.match(/^rotate\(([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\)$/);
        if (!r) throw new Error(`transform ${tr} in ${file}`);
        const a = (+r[1] * Math.PI) / 180, cx = +r[2], cy = +r[3], cos = Math.cos(a), sin = Math.sin(a);
        // translate(cx, cy) · rotate(a) · translate(−cx, −cy)
        spec += `, transform: CGAffineTransform(a: ${cos}, b: ${sin}, c: ${-sin}, d: ${cos}, tx: ${cx - cos * cx + sin * cy}, ty: ${cy - sin * cx - cos * cy})`;
      }
      paths.push(spec + ')');
    }
    out.push(`        "${file}": SignalIconData(width: ${w}, height: ${h}, viewBox: CGRect(x: 0, y: 0, width: ${w}, height: ${h}), paths: [`);
    for (const p of paths) out.push(`            ${p},`);
    out.push('        ]),');
    count++;
  }
}

out.push('    ]', '}', '');
writeFileSync(join(root, 'Packages/SignalUI/Sources/SignalUI/Tokens/SignalIcons.generated.swift'), out.join('\n'));
console.log(count, 'icons;', skipped.length, 'skipped:', skipped.join(' '));
