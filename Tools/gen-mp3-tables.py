#!/usr/bin/env python3 -I
"""Generate Packages/SignalCodecs/Sources/AudioMP3/MP3Tables.generated.swift from FFmpeg's
libavcodec/mpegaudiodec_common.c and mpegaudiodsp_data.c (n7.1, LGPL-2.1+; the values are
ISO/IEC 11172-3 / 13818-3's tables): the Layer III Huffman tables (B.7; given in FFmpeg as
code lengths and symbols in code order, the codes being assigned canonically as FFmpeg's
ff_vlc_init_from_lengths does), the count1 quadruple tables, scalefactor band sizes (B.8),
pretab, slen/LSF tables and the synthesis window D (B.3, integer ×65536).

Usage: Tools/gen-mp3-tables.py <path/to/mpegaudiodec_common.c> <path/to/mpegaudiodsp_data.c>
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Packages/SignalCodecs/Sources/AudioMP3/MP3Tables.generated.swift")

def clean(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)

common = clean(open(sys.argv[1]).read())
dsp = clean(open(sys.argv[2]).read())

def body(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("missing " + name)
    return m.group(2)

def ints(src, name):
    return [int(v, 0) for v in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", body(src, name))]

def swift(name, type_, values, per=16):
    rows = [", ".join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per)]
    return f"    static let {name}: [{type_}] = [\n        " + ",\n        ".join(rows) + ",\n    ]\n"

def nested(name, type_, rows):
    inner = ",\n        ".join("[" + ", ".join(str(v) for v in r) + "]" for r in rows)
    return f"    static let {name}: [[{type_}]] = [\n        {inner},\n    ]\n"

lens = ints(common, "mpa_hufflens")
syms = ints(common, "mpa_huffsymbols")
sizes = [n + 1 for n in ints(common, "mpa_huff_sizes_minus_one")]
assert sum(sizes) == len(lens) == len(syms), (sum(sizes), len(lens), len(syms))
names = [1, 2, 3, 5, 6, 7, 8, 9, 10, 11, 12, 13, 15, 16, 24]
out = ["// Generated by Tools/gen-mp3-tables.py from FFmpeg libavcodec/mpegaudiodec_common.c and\n",
       "// mpegaudiodsp_data.c (n7.1); do not edit. ISO/IEC 11172-3 Tables B.3, B.7, B.8.\n\n",
       "enum MP3Tables {\n"]
pos = 0
code_tables, len_tables, sym_tables = [], [], []
for t, n in zip(names, sizes):
    l, s = lens[pos:pos + n], syms[pos:pos + n]
    pos += n
    code, codes = 0, []
    for ln in l:                       # ff_vlc_init_from_lengths: increasing canonical codes
        assert code & ((1 << (32 - ln)) - 1) == 0
        codes.append(code >> (32 - ln))
        code += 1 << (32 - ln)
    assert code == 1 << 32, f"table {t} is not complete"
    out.append(swift(f"huffCodes{t}", "UInt32", codes))
    out.append(swift(f"huffLengths{t}", "UInt8", l))
    out.append(swift(f"huffSymbols{t}", "Int", s))
    code_tables.append(f"huffCodes{t}"); len_tables.append(f"huffLengths{t}"); sym_tables.append(f"huffSymbols{t}")
out.append("    /// FFmpeg's table numbering: index 1…15 = Huffman tables 1, 2, 3, 5, 6, 7, 8, 9, 10, 11, 12, 13, 15, 16, 24.\n")
out.append("    static let huffCodes: [[UInt32]] = [[], " + ", ".join(code_tables) + "]\n")
out.append("    static let huffLengths: [[UInt8]] = [[], " + ", ".join(len_tables) + "]\n")
out.append("    static let huffSymbols: [[Int]] = [[], " + ", ".join(sym_tables) + "]\n")
hd = ints(common, "ff_mpa_huff_data")
out.append("    /// table_select 0…31 → (table index above, 0 = all zero; linbits).\n")
out.append(swift("huffTable", "UInt8", hd[0::2]))
out.append(swift("huffLinbits", "UInt8", hd[1::2]))
qc, qb = ints(common, "mpa_quad_codes"), ints(common, "mpa_quad_bits")
out.append(nested("quadCodes", "UInt32", [qc[:16], qc[16:]]))
out.append(nested("quadBits", "UInt8", [qb[:16], qb[16:]]))
bl = ints(common, "ff_band_size_long")
out.append("    /// By sample-rate index 0…8 = 44100, 48000, 32000, 22050, 24000, 16000, 11025, 12000, 8000 Hz.\n")
out.append(nested("bandSizeLong", "UInt8", [bl[i:i + 22] for i in range(0, len(bl), 22)]))
bs = ints(common, "ff_band_size_short")
out.append(nested("bandSizeShort", "UInt8", [bs[i:i + 13] for i in range(0, len(bs), 13)]))
out.append(swift("pretab", "UInt8", ints(common, "ff_mpa_pretab")[22:], per=22))
sl = ints(common, "ff_slen_table")
out.append(nested("slen", "UInt8", [sl[:16], sl[16:]]))
nsf = ints(common, "ff_lsf_nsf_table")
out.append("    /// [partition table][block kind: long, short, mixed][4 partitions] (13818-3 Table B.6).\n")
out.append("    static let lsfPartitions: [[[UInt8]]] = [\n" + "".join(
    "        [" + ", ".join("[" + ", ".join(str(v) for v in nsf[t * 12 + k * 4: t * 12 + k * 4 + 4]) + "]" for k in range(3)) + "],\n"
    for t in range(6)) + "    ]\n")
win = ints(dsp, "ff_mpa_enwindow")
assert len(win) == 257
out.append("    /// Synthesis window D[0…256] × 65536 (exact: the standard's values are multiples of 2⁻¹⁶).\n")
out.append(swift("synthesisWindowHalf", "Int32", win))
out.append("}\n")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("".join(out))
print("wrote", OUT)
