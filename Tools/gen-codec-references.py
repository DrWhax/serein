def step_audioservice(corpora):
    """Fixtures for SignalMediaService's audio requests: a few MP3/AAC files from the codec
    references, with ffmpeg's default (trimmed: LAME delay/padding, MP4 edit list) decode at
    the native rate summarised as its frame count and upstream's waveform (waveformBuilder.std.ts
    over the interleaved samples)."""
    dst = os.path.join(ROOT, "Packages/SignalMediaService/Tests/SignalMediaDecoderTests/Resources/Audio")
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    files = ["MP3/stereo_44100_vbr_q7.mp3", "MP3/voice_mono_44100_vbr_q7.mp3", "AAC/stereo_48000_96k.m4a",
             "AAC/mono_22050_48k.m4a", "AAC/mono_8000_16k.aac", "AAC/stereo_44100_apple_128k.m4a"]
    def to_peak(ms):
        val = max(0.0, 10 * math.log10(ms) + 60) / 60 if ms > 0 else 0.0
        return int(math.floor(val * 255 + 0.5))
    def waveform(samples):
        wf = [0.0] * 100
        length = shift = 0
        for x in samples:
            index = length >> shift
            if index >= 100:
                for i in range(50):
                    wf[i] = (wf[2 * i] + wf[2 * i + 1]) / 2
                for i in range(50, 100):
                    wf[i] = 0.0
                shift += 1
                index = 50
            wf[index] += x * x / (1 << shift)
            length += 1
        n = length >> shift
        last = length % (1 << shift)
        if last:
            wf[n] = wf[n] * (1 << shift) / last
            n += 1
        return [to_peak(wf[i]) for i in range(n)]
    refs = {}
    for f in files:
        name = os.path.basename(f)
        shutil.copy(os.path.join(RES, f), os.path.join(dst, name))
        raw = subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", os.path.join(dst, name), "-f", "f32le", "-c:a", "pcm_f32le", "-"],
                             check=True, capture_output=True).stdout
        samples = struct.unpack("<%df" % (len(raw) // 4), raw)
        probe = json.loads(subprocess.run(["ffprobe", "-v", "error", "-show_streams", "-of", "json", os.path.join(dst, name)], check=True, capture_output=True).stdout)
        ch = int(probe["streams"][0]["channels"])
        refs[name] = {"frames": len(samples) // ch, "channels": ch, "sampleRate": int(probe["streams"][0]["sample_rate"]), "waveform": waveform(samples)}
    json.dump(refs, open(os.path.join(dst, "references.json"), "w"), indent=0, sort_keys=True)
    print("audioservice:", len(files), "files")

def step_mp3conformance(corpora):
    """The ISO/IEC 11172-4 Layer III compliance bitstreams (from FFmpeg's FATE suite,
    fate-suite.ffmpeg.org/mp3-conformance): intensity stereo, mixed blocks, every Huffman
    table, CRC, mode changes. ffmpeg's float decoder output is the reference."""
    src = os.path.join(corpora, "mp3-conformance")
    dst = os.path.join(RES, "MP3Conformance")
    shutil.rmtree(dst, ignore_errors=True)
    os.makedirs(dst)
    names = sorted(n for n in os.listdir(src) if n.endswith(".bit"))
    for n in names:
        shutil.copy(os.path.join(src, n), os.path.join(dst, n))
        if n == "he_free.bit":
            continue    # free format: refused by the decoder, no reference
        # he_mode switches between mono and stereo modes: decode to stereo (ffmpeg upmixes the
        # mono frames at −3 dB, sqrt(1/2) on each side).
        layout = ["-ac", "2"] if n == "he_mode.bit" else []
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-flags2", "skip_manual", "-f", "mp3", "-i", os.path.join(dst, n)]
                       + layout + ["-f", "f32le", "-c:a", "pcm_f32le", os.path.join(dst, n + ".f32")], check=True)
    open(os.path.join(dst, "SOURCE.md"), "w").write(
        "ISO/IEC 11172-4 MPEG-1 Layer III compliance bitstreams as distributed in FFmpeg's FATE suite\n"
        "(https://fate-suite.ffmpeg.org/mp3-conformance/). <name>.f32: ffmpeg's float decoder output,\n"
        "interleaved, -flags2 skip_manual. he_free.bit is free-format and has no reference.\n")
    print("mp3conformance:", len(names), "files")

