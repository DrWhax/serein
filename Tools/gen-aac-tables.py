#!/usr/bin/env python3 -I
"""Generate Packages/SignalCodecs/Sources/AudioAAC/AACTables.generated.swift from FFmpeg's
libavcodec/aactab.c (n7.1, LGPL-2.1+; the values are ISO/IEC 14496-3's tables):
scalefactor and spectral Huffman codebooks (Tables 4.A.1–4.A.12), scalefactor band offsets
(Tables 4.129–4.147), TNS maximum bands and coefficient maps.

Usage: Tools/gen-aac-tables.py <path/to/aactab.c>
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Packages/SignalCodecs/Sources/AudioAAC/AACTables.generated.swift")

src = open(sys.argv[1]).read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)

def array(name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("missing " + name)
    return [v.strip() for v in m.group(1).replace("\n", " ").split(",") if v.strip()]

def ints(name):
    return [int(v.rstrip("UuLl"), 0) for v in array(name)]

def floats(name):
    return [float(v.rstrip("fF")) for v in array(name)]

def swift(name, type_, values, per=16):
    rows = [", ".join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per)]
    return f"    static let {name}: [{type_}] = [\n        " + ",\n        ".join(rows) + ",\n    ]\n"

out = ["// Generated by Tools/gen-aac-tables.py from FFmpeg libavcodec/aactab.c (n7.1); do not edit.\n",
       "// ISO/IEC 14496-3 Tables 4.A.1–4.A.12 (Huffman), 4.129–4.147 (scalefactor bands), 4.155 (TNS).\n\n",
       "enum AACTables {\n"]
out.append(swift("scalefactorCodes", "UInt32", ints("ff_aac_scalefactor_code")))
out.append(swift("scalefactorBits", "UInt8", ints("ff_aac_scalefactor_bits")))
for i in range(1, 12):
    out.append(swift(f"codes{i}", "UInt16", ints(f"codes{i}")))
    out.append(swift(f"bits{i}", "UInt8", ints(f"bits{i}")))
out.append("    static let spectralCodes: [[UInt16]] = [" + ", ".join(f"codes{i}" for i in range(1, 12)) + "]\n")
out.append("    static let spectralBits: [[UInt8]] = [" + ", ".join(f"bits{i}" for i in range(1, 12)) + "]\n")
long_rates = ["96", "96", "64", "48", "48", "32", "24", "24", "16", "16", "16", "8", "8"]
short_rates = ["96", "96", "96", "48", "48", "48", "24", "24", "16", "16", "16", "8", "8"]
for r in sorted(set(long_rates)):
    out.append(swift(f"swbOffsetLong{r}", "UInt16", ints(f"swb_offset_1024_{r}")))
for r in sorted(set(short_rates)):
    out.append(swift(f"swbOffsetShort{r}", "UInt16", ints(f"swb_offset_128_{r}")))
out.append("    /// By sampling frequency index (0 = 96 kHz … 12 = 7350 Hz).\n")
out.append("    static let swbOffsetLong: [[UInt16]] = [" + ", ".join(f"swbOffsetLong{r}" for r in long_rates) + "]\n")
out.append("    static let swbOffsetShort: [[UInt16]] = [" + ", ".join(f"swbOffsetShort{r}" for r in short_rates) + "]\n")
out.append(swift("numSwbLong", "UInt8", ints("ff_aac_num_swb_1024")))
out.append(swift("numSwbShort", "UInt8", ints("ff_aac_num_swb_128")))
out.append(swift("tnsMaxBandsLong", "UInt8", ints("ff_tns_max_bands_1024")))
out.append(swift("tnsMaxBandsShort", "UInt8", ints("ff_tns_max_bands_128")))
for n in ["tns_tmp2_map_1_3", "tns_tmp2_map_0_3", "tns_tmp2_map_1_4", "tns_tmp2_map_0_4"]:
    camel = "tns" + "".join(p.capitalize() for p in n.split("_")[2:])
    out.append(swift(camel, "Float", floats(n), per=4))
out.append("}\n")
open(OUT, "w").write("".join(out))
print("wrote", OUT)
