#!/usr/bin/env node
// Generates Packages/SignalUI/Sources/SignalUI/Tokens/AxoTokensTables.generated.swift from
// the data tables in upstream ts/axo/AxoTokens.std.ts (avatar colours, gradients and
// presets, contact name colours, chat-bubble presets), preserving their order (upstream
// picks avatar colours and gradients by `hash % count` over that order).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'Signal-Desktop/ts/axo/AxoTokens.std.ts'), 'utf8');
const block = (start) => {
  const i = src.indexOf(start);
  if (i < 0) throw new Error(`missing ${start}`);
  const open = src.indexOf('{', i + start.length - 1);
  let depth = 0;
  for (let j = open; j < src.length; j++) {
    if (src[j] === '{' || src[j] === '[') depth++;
    if (src[j] === '}' || src[j] === ']') { depth--; if (depth === 0) return src.slice(open, j + 1); }
  }
  throw new Error(`unterminated ${start}`);
};
const hex = (h) => `RGBA(hex: 0x${h.slice(1)})`;
const out = ['// Generated by Tools/gen-axo-tables.mjs from Signal-Desktop/ts/axo/AxoTokens.std.ts. Do not edit.', '', 'enum AxoTokensTables {'];

const avatarColors = [...block('const Colors: Record<ColorName, ColorValues> = {').matchAll(/(A\d+): \{ bg: hexColor\('(#\w+)'\), fg: hexColor\('(#\w+)'\) \}/g)];
out.push('    /// Avatar colours A100…A210 in upstream order (getColorNameByHash: hash % 12).');
out.push('    static let avatarColors: [(name: String, bg: RGBA, fg: RGBA)] = [');
for (const m of avatarColors) out.push(`        ("${m[1]}", ${hex(m[2])}, ${hex(m[3])}),`);
out.push('    ]');

const gradIdx = src.indexOf('const Gradients: ReadonlyArray<GradientValues> = [');
const gradients = [...src.slice(gradIdx, src.indexOf('];', gradIdx)).matchAll(/start: hexColor\('(#\w+)'\), end: hexColor\('(#\w+)'\)/g)];
out.push('    /// Avatar gradients (getGradientValuesByHash: hash % 20).');
out.push('    static let avatarGradients: [(start: RGBA, end: RGBA)] = [');
for (const m of gradients) out.push(`        (${hex(m[1])}, ${hex(m[2])}),`);
out.push('    ]');

for (const [name, start] of [['contactPresets', 'const ContactPresetColors: Record<ContactPresetName, ColorName> = {'],
  ['groupPresets', 'const GroupPresetColors: Record<GroupPresetName, ColorName> = {']]) {
  const rows = [...block(start).matchAll(/(\w+): '(A\d+)'/g)];
  out.push(`    static let ${name}: [(name: String, color: String)] = [`);
  for (const m of rows) out.push(`        ("${m[1]}", "${m[2]}"),`);
  out.push('    ]');
}

const contactStart = src.indexOf('export namespace Contact');
const contact = [...src.slice(contactStart).matchAll(/'(\d{3})': \{ light: hexColor\('(#\w+)'\), dark: hexColor\('(#\w+)'\) \}/g)];
out.push('    /// Contact (group member) name colours 000…350.');
out.push('    static let contactColors: [(name: String, color: AxoColor)] = [');
for (const m of contact) out.push(`        ("${m[1]}", AxoColor(light: ${hex(m[2])}, dark: ${hex(m[3])})),`);
out.push('    ]');

const solid = [...block('const SolidPresets: Record<SolidPresetName, HexColor> = {').matchAll(/(\w+): hexColor\('(#\w+)'\)/g)];
out.push('    static let chatBubbleSolids: [(name: String, color: RGBA)] = [');
for (const m of solid) out.push(`        ("${m[1]}", ${hex(m[2])}),`);
out.push('    ]');
const bubbleGradients = [...block('export const Gradients: Record<GradientPresetName, Gradient> = {')
  .matchAll(/(\w+): \{\s*deg: (\d+),\s*start: hexColor\('(#\w+)'\),\s*end: hexColor\('(#\w+)'\),?\s*\}/g)];
out.push('    static let chatBubbleGradients: [(name: String, deg: Double, start: RGBA, end: RGBA)] = [');
for (const m of bubbleGradients) out.push(`        ("${m[1]}", ${m[2]}, ${hex(m[3])}, ${hex(m[4])}),`);
out.push('    ]', '}', '');
writeFileSync(join(root, 'Packages/SignalUI/Sources/SignalUI/Tokens/AxoTokensTables.generated.swift'), out.join('\n'));
console.log({ avatarColors: avatarColors.length, gradients: gradients.length, contact: contact.length, solid: solid.length, bubbleGradients: bubbleGradients.length });
