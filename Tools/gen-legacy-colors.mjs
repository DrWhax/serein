#!/usr/bin/env node
// Generates Packages/SignalUI/Sources/SignalUI/Tokens/LegacyColors.generated.swift from
// upstream stylesheets/_variables.scss: the SCSS `$color-*` palette that the pre-Axo
// components (stylesheets/components/*.scss) are styled with, as `RGBA` constants
// (`$color-gray-15` → `LegacyColor.gray15`). Light/dark pairs are chosen per component,
// as upstream's `@include light-theme { … } @include dark-theme { … }` blocks do.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'Signal-Desktop/stylesheets/_variables.scss'), 'utf8');
const values = new Map();
const out = ['// Generated by Tools/gen-legacy-colors.mjs from Signal-Desktop/stylesheets/_variables.scss. Do not edit.', '',
  'public enum LegacyColor {'];
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, '_$1');
const hexRGBA = (h) => {
  const x = h.length === 4 ? h.slice(1).split('').map((c) => c + c).join('') : h.slice(1);
  return [parseInt(x.slice(0, 2), 16) / 255, parseInt(x.slice(2, 4), 16) / 255, parseInt(x.slice(4, 6), 16) / 255, 1];
};
for (const m of src.matchAll(/^\$color-([\w-]+):\s*([^;]+);/gm)) {
  const [, name, raw] = m;
  if (values.has(name)) continue;   // $color-white-alpha-40 is declared twice
  let v = null;
  const r = raw.trim();
  let mm;
  if ((mm = r.match(/^#[0-9a-fA-F]{3,6}$/))) v = hexRGBA(r);
  else if ((mm = r.match(/^rgba\(\$color-([\w-]+),\s*([\d.]+)\)$/))) { const b = values.get(mm[1]); if (b) v = [b[0], b[1], b[2], +mm[2]]; }
  else if ((mm = r.match(/^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/))) v = [mm[1] / 255, mm[2] / 255, mm[3] / 255, +mm[4]];
  else if ((mm = r.match(/^\$color-([\w-]+)$/))) v = values.get(mm[1]);
  if (!v) { console.error('skip', name, r); continue; }
  values.set(name, v);
  const fmt = (x) => `${Math.round(x * 1e6) / 1e6}`;
  out.push(`    /// \`$color-${name}\`: ${r}`);
  out.push(`    public static let ${camel(name)} = RGBA(${v.map(fmt).join(', ')})`);
}
out.push('}', '');
writeFileSync(join(root, 'Packages/SignalUI/Sources/SignalUI/Tokens/LegacyColors.generated.swift'), out.join('\n'));
console.log(values.size, 'legacy colors');
