// Calling codes for the regions in Signal-Desktop/build/country-display-names.json, from the
// pinned google-libphonenumber (with getCountryData.dom.ts's special cases), as Swift:
// Packages/SignalUI/Sources/SignalUI/Tokens/CountryCodes.generated.swift.
//   node Tools/gen-country-codes.mjs
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, '.cache/storybook-desktop/package.json'));
const { PhoneNumberUtil } = require('google-libphonenumber');
const util = PhoneNumberUtil.getInstance();
const names = JSON.parse(readFileSync(join(root, 'Signal-Desktop/build/country-display-names.json'), 'utf8'));
const special = { AQ: 672, BV: 55, IC: 34, EA: 34, DG: 246, TF: 262, HM: 672, XK: 383, PN: 64, GS: 500, UM: 1 };
const regions = Object.keys(names.en).sort();
const lines = [];
for (const region of regions) {
  if (region === 'CP') continue;    // Clipperton Island: no calling code (upstream throws)
  const code = special[region] ?? util.getCountryCodeForRegion(region);
  if (!code) continue;
  lines.push(`        "${region}": ${code},`);
}
writeFileSync(join(root, 'Packages/SignalUI/Sources/SignalUI/Tokens/CountryCodes.generated.swift'), [
  '// Generated by Tools/gen-country-codes.mjs from google-libphonenumber. Do not edit.', '',
  'enum CountryCodesTable {', '    /// Region → country calling code.', '    static let codes: [String: Int] = [', ...lines, '    ]', '}', '',
].join('\n'));
console.log('regions:', lines.length);
