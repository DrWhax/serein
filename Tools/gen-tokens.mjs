#!/usr/bin/env node
// Generates Packages/SignalUI/Sources/SignalUI/Tokens/AxoTokens.generated.swift from the
// tokens Chromium resolved in upstream's Storybook (Tools/capture-storybook.mjs --tokens):
// every --axo-color-* in light and dark as exact sRGB, the elevation shadows layer by
// layer, radii, spacing, blurs and motion constants from ts/axo/_tailwind-theme/*.css.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, '.cache/axo-tokens.json'), 'utf8'));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const num = (x) => {
  const v = Math.min(1, Math.max(0, x));
  const r = Math.round(v * 1e6) / 1e6;
  return Number.isInteger(r) ? `${r}` : `${r}`;
};
const rgba = (c) => `RGBA(${c.map(num).join(', ')})`;
const rem = (raw) => (raw.endsWith('rem') ? parseFloat(raw) * 16 : parseFloat(raw));
const lines = [
  '// Generated by Tools/gen-tokens.mjs from upstream Storybook (Chromium-resolved CSS tokens). Do not edit.',
  '// Source: Signal-Desktop/ts/axo/_tailwind-theme/*.css',
  '',
  'import CoreGraphics',
  '',
  'extension AxoColor {',
];
const colors = Object.keys(t.light).filter((k) => (k.startsWith('--axo-color-') || k.startsWith('--axo-shadow-color-')) && t.light[k].srgb).sort();
for (const k of colors) {
  const name = k.startsWith('--axo-color-') ? camel(k.slice('--axo-color-'.length)) : camel(k.slice('--axo-'.length));
  lines.push(`    /// \`${k}\``);
  lines.push(`    public static let ${name} = AxoColor(light: ${rgba(t.light[k].srgb)}, dark: ${rgba(t.dark[k].srgb)})`);
}
lines.push('}', '', 'extension AxoShadow {');
const shadows = Object.keys(t.light).filter((k) => /^--(base-)?shadow-/.test(k) && t.light[k].shadow).sort();
for (const k of shadows) {
  const layers = (theme) => `[${t[theme][k].shadow.map((l) => `.init(inset: ${l.inset}, x: ${l.x}, y: ${l.y}, blur: ${l.blur}, spread: ${l.spread}, color: ${rgba(l.srgb)})`).join(', ')}]`;
  lines.push(`    /// \`${k}\``);
  lines.push(`    public static let ${camel(k.slice(2))} = AxoShadow(light: ${layers('light')},`);
  lines.push(`                                          dark: ${layers('dark')})`);
}
lines.push('}', '', 'public enum AxoRadius {');
for (const k of Object.keys(t.light).filter((k) => k.startsWith('--radius-')).sort()) {
  lines.push(`    public static let ${camel(k.slice('--radius-'.length)).replace(/^(\d)/, '_$1')}: CGFloat = ${rem(t.light[k].raw)}`);
}
lines.push('}', '', 'public enum AxoBlur {');
for (const k of Object.keys(t.light).filter((k) => k.startsWith('--blur-')).sort()) {
  lines.push(`    public static let ${camel(k.slice('--blur-'.length))}: CGFloat = ${rem(t.light[k].raw)}`);
}
lines.push('}', '', 'public enum AxoMetrics {');
lines.push(`    /// Tailwind \`--spacing\`: 1 unit of p-*, m-*, gap-*, size-* …`);
lines.push(`    public static let spacing: CGFloat = ${rem(t.light['--spacing'].raw)}`);
lines.push(`    /// \`--default-transition-duration\` (s)`);
lines.push(`    public static let transitionDuration: Double = ${parseFloat(t.light['--default-transition-duration'].raw)}`);
const ease = t.light['--ease-out-cubic'].raw.match(/[\d.]+/g).map(Number);
lines.push(`    /// \`--ease-out-cubic\` control points`);
lines.push(`    public static let easeOutCubic: (CGFloat, CGFloat, CGFloat, CGFloat) = (${ease.join(', ')})`);
lines.push('}', '');
writeFileSync(join(root, 'Packages/SignalUI/Sources/SignalUI/Tokens/AxoTokens.generated.swift'), lines.join('\n'));
console.log(`${colors.length} colors, ${shadows.length} shadows`);
