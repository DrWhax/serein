#!/usr/bin/env python3 -I
"""Generate Packages/SignalCodecs/Sources/VideoH264/H264Tables.generated.swift from FFmpeg's
libavcodec (n7.1, LGPL-2.1+; the values are ITU-T H.264's tables):
  h264_cavlc.c    coeff_token (Table 9-5), total_zeros (9-7, 9-9), run_before (9-10) VLCs
  h264_cabac.c    context initialisation m, n (Tables 9-12 … 9-33), residual context offsets
  cabac.c         rangeTabLPS (Table 9-44) and transIdxLPS (9-45), unpacked from FFmpeg's layout
  h264_loopfilter.c  alpha', beta' (Table 8-16), tC0 (8-17)
  h264_ps.c       Default_4x4_Intra/Inter, Default_8x8_Intra/Inter (Table 7-3, 7-4; raster order)

Usage: Tools/gen-h264-tables.py <dir with those FFmpeg files>
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Packages/SignalCodecs/Sources/VideoH264/H264Tables.generated.swift")
SRC = sys.argv[1]

def load(name):
    s = open(os.path.join(SRC, name)).read()
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)

def body(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\)?\s*(\[[^\]]*\]\s*)+=\s*\{", src)
    if not m:
        raise SystemExit("missing " + name)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{": depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1:j]
    raise SystemExit("unterminated " + name)

def ints(src, name):
    return [int(v, 0) for v in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", body(src, name))]

def rows(src, name, width):
    """A 2-D table whose rows may be shorter than `width` (C zero-fills them)."""
    out = []
    for row in re.findall(r"\{([^{}]*)\}", body(src, name)):
        vals = [int(v, 0) for v in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", row)]
        assert len(vals) <= width, (name, len(vals))
        out += vals + [0] * (width - len(vals))
    return out

def swift(name, type_, values, per=16):
    rows = [", ".join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per)]
    return f"    static let {name}: [{type_}] = [\n        " + ",\n        ".join(rows) + ",\n    ]\n"

cavlc = load("h264_cavlc.c")
cabac = load("h264_cabac.c")
cabact = load("cabac.c")
lf = load("h264_loopfilter.c")
ps = load("h264_ps.c")
out = ["// Generated by Tools/gen-h264-tables.py from FFmpeg n7.1 (libavcodec); do not edit.\n",
       "// ITU-T H.264 Tables 7-3/7-4, 8-16/8-17, 9-5…9-10, 9-12…9-33, 9-44/9-45.\n\n",
       "enum H264Tables {\n"]

# CAVLC. coeff_token: 4 tables (nC 0–1, 2–3, 4–7, 8+) of [trailingOnes 0…3][totalCoeff 0…16]
# laid out as 4*17 entries index = totalCoeff*4 + trailingOnes.
ctl, ctb = ints(cavlc, "coeff_token_len"), ints(cavlc, "coeff_token_bits")
out.append(swift("coeffTokenLength", "UInt8", ctl))
out.append(swift("coeffTokenCode", "UInt32", ctb))
out.append(swift("chromaDCCoeffTokenLength", "UInt8", ints(cavlc, "chroma_dc_coeff_token_len")))
out.append(swift("chromaDCCoeffTokenCode", "UInt32", ints(cavlc, "chroma_dc_coeff_token_bits")))
out.append("    /// total_zeros, row i for TotalCoeff i + 1 (rows 0…14; row 15 unused), 16 entries each.\n")
out.append(swift("totalZerosLength", "UInt8", rows(cavlc, "total_zeros_len", 16)))
out.append(swift("totalZerosCode", "UInt32", rows(cavlc, "total_zeros_bits", 16)))
out.append(swift("chromaDCTotalZerosLength", "UInt8", rows(cavlc, "chroma_dc_total_zeros_len", 4), per=4))
out.append(swift("chromaDCTotalZerosCode", "UInt32", rows(cavlc, "chroma_dc_total_zeros_bits", 4), per=4))
out.append("    /// run_before, row i for zerosLeft i + 1 (rows 0…5) and ≥ 7 (row 6), 16 entries each.\n")
out.append(swift("runBeforeLength", "UInt8", rows(cavlc, "run_len", 16)))
out.append(swift("runBeforeCode", "UInt32", rows(cavlc, "run_bits", 16)))

# CABAC initialisation (m, n) pairs.
ci = ints(cabac, "cabac_context_init_I")
assert len(ci) == 2048
out.append("    /// (m, n) per context for I slices, 1024 contexts interleaved.\n")
out.append(swift("cabacInitI", "Int8", ci))
cp = ints(cabac, "cabac_context_init_PB")
assert len(cp) == 3 * 2048
out.append("    /// (m, n) per context for P/B slices, by cabac_init_idc 0…2.\n")
out.append(swift("cabacInitPB", "Int8", cp))

# rangeTabLPS and transIdxLPS from FFmpeg's packed table: lps_range[q*128 + 2p + m] = range;
# mlps_state[128 + s] = MPS successor, mlps_state[127 - s] = LPS successor, s = 2p + m.
tab = [v & 0xFF for v in ints(cabact, "ff_h264_cabac_tables")]  # stored as signed literals
lps = tab[512:1024]
range_lps = [[lps[q * 128 + 2 * p] for q in range(4)] for p in range(64)]
mlps = tab[1024:1280]
trans_lps = [mlps[127 - 2 * p] >> 1 for p in range(64)]
trans_mps = [mlps[128 + 2 * p] >> 1 for p in range(64)]
assert trans_mps[:62] == [min(p + 1, 62) for p in range(62)], trans_mps
out.append(swift("rangeTabLPS", "UInt8", [v for row in range_lps for v in row], per=4))
out.append(swift("transIdxLPS", "UInt8", trans_lps))

def static(src, name):
    m = re.search(r"static const \w+ " + re.escape(name) + r"\s*(\[[^\]]*\]\s*)+=\s*\{", src)
    if not m: raise SystemExit("missing " + name)
    return ints(src, name)
out.append(swift("significantCoeffFlagOffset", "Int", static(cabac, "significant_coeff_flag_offset"), per=14))
out.append(swift("lastCoeffFlagOffset", "Int", static(cabac, "last_coeff_flag_offset"), per=14))
out.append(swift("coeffAbsLevelM1Offset", "Int", static(cabac, "coeff_abs_level_m1_offset"), per=14))
out.append("    /// significant_coeff_flag ctxIdxInc for 8x8 blocks, frame (row 0) and field (row 1).\n")
out.append(swift("significantCoeffFlagOffset8x8", "UInt8", static(cabac, "significant_coeff_flag_offset_8x8"), per=21))
out.append(swift("lastCoeffFlagOffset8x8", "UInt8", tab[1280:1280 + 63], per=21))
out.append(swift("codedBlockFlagBase", "Int", static(cabac, "base_ctx"), per=14))

# Loop filter: FFmpeg pads by 52 each side (indexA may be out of range before clipping).
alpha, beta, tc0 = ints(lf, "alpha_table"), ints(lf, "beta_table"), ints(lf, "tc0_table")
out.append(swift("alpha", "UInt8", alpha[52:104]))
out.append(swift("beta", "UInt8", beta[52:104]))
out.append("    /// tC0 by indexA, bS 1…3 (3 entries per indexA).\n")
out.append(swift("tc0", "UInt8", [v for i in range(52, 104) for v in tc0[i * 4 + 1:i * 4 + 4]], per=12))

d4, d8 = ints(ps, "default_scaling4"), ints(ps, "default_scaling8")
out.append("    /// Flat-free defaults, raster order: [intra, inter].\n")
out.append(swift("defaultScaling4", "UInt8", d4))
out.append(swift("defaultScaling8", "UInt8", d8))
out.append("}\n")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("".join(out))
print("wrote", OUT)
