#!/usr/bin/env node
// Generates Packages/SignalUI/Sources/SignalUI/Tokens/AxoSymbolDefs.generated.swift from
// upstream ts/axo/_internal/AxoSymbolDefs.generated.std.ts (Signal Symbols font glyphs:
// BASE / RTL / WIDE / WIDE_RTL tables and the same icon / inline-glyph lookup rules).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'Signal-Desktop/ts/axo/_internal/AxoSymbolDefs.generated.std.ts'), 'utf8');
const table = (name) => {
  const body = src.match(new RegExp(`const ${name}: Record<string, string> = \\{([\\s\\S]*?)\\n\\};`))[1];
  return [...body.matchAll(/'([^']+)': '\\u\{([0-9A-F]+)\}'/g)].map((m) => [m[1], m[2]]);
};
const out = ['// Generated by Tools/gen-symbols.mjs from Signal-Desktop/ts/axo/_internal/AxoSymbolDefs.generated.std.ts. Do not edit.', '',
  'enum AxoSymbolDefs {'];
const counts = {};
for (const name of ['BASE', 'RTL', 'WIDE', 'WIDE_RTL']) {
  const rows = table(name);
  counts[name] = rows.length;
  out.push(`    static let ${({ BASE: 'base', RTL: 'rtl', WIDE: 'wide', WIDE_RTL: 'wideRTL' })[name]}: [String: Character] = [`);
  for (const [k, v] of rows) out.push(`        "${k}": "\\u{${v}}",`);
  out.push('    ]');
}
out.push('    /// `_getAllAxoSymbolNames()`: BASE keys in upstream order.');
out.push(`    static let allNames: [String] = [${table('BASE').map(([k]) => `"${k}"`).join(', ')}]`);
out.push('}', '');
writeFileSync(join(root, 'Packages/SignalUI/Sources/SignalUI/Tokens/AxoSymbolDefs.generated.swift'), out.join('\n'));
console.log(counts);
